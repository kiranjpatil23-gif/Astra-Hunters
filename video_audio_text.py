if not video_path.exists():
    raise FileNotFoundError("Video not found in Colab.")

# Create output folders
session_dir = Path("/content/presentation_analysis/test_session")
original_dir = session_dir / "original"
audio_dir = session_dir / "audio"
metadata_dir = session_dir / "metadata"

for folder in [original_dir, audio_dir, metadata_dir]:
    folder.mkdir(parents=True, exist_ok=True)

# Preserve a copy of the original video
original_video_path = original_dir / video_path.name

if not original_video_path.exists():
    import shutil
    shutil.copy2(video_path, original_video_path)

# Output 1: Preserve the original encoded audio without re-encoding
original_audio_path = audio_dir / "audio_original.mka"

command = [
    "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
    "-i", str(original_video_path),
    "-map", "0:a:0",
    "-vn",
    "-c:a", "copy",
    str(original_audio_path)
]

result = subprocess.run(command, capture_output=True, text=True)

if result.returncode != 0:
    raise RuntimeError("Original audio extraction failed:\n" + result.stderr)

# Output 2: Decode the audio into WAV without removing pauses or speech
analysis_wav_path = audio_dir / "audio_analysis.wav"

command = [
    "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
    "-i", str(original_video_path),
    "-map", "0:a:0",
    "-vn",
    "-c:a", "pcm_s16le",
    str(analysis_wav_path)
]

result = subprocess.run(command, capture_output=True, text=True)

if result.returncode != 0:
    raise RuntimeError("WAV creation failed:\n" + result.stderr)

# Verify both files
print("AUDIO EXTRACTION COMPLETED")
print("-" * 45)

for path in [original_audio_path, analysis_wav_path]:
    print(f"\nFile: {path.name}")
